"""Turn the Playwright result files in results/ into docs/BROWSER_VERIFICATION.md.
Nothing is invented: every number comes from the JSON the browser runs wrote. Files: results.json (the original Edge desktop run) and
results-<browser>[-mobile].json (runs made with PFI_BROWSER / PFI_MOBILE)."""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
files = sorted((HERE / "results").glob("results*.json"))
if not files:
    sys.exit("no results/*.json - run `npx playwright test` first; nothing was written")


def label(f: Path) -> str:
    n = f.stem.replace("results", "").strip("-") or "msedge"
    return {"msedge": "Microsoft Edge, desktop", "chrome": "Google Chrome, desktop",
            "chromium": "Chromium (Playwright bundled), desktop", "chromium-mobile": "Chromium, mobile viewport 390x844 (touch emulation)", "firefox": "Firefox 132, desktop",
            "msedge-mobile": "Microsoft Edge, mobile viewport 390x844 (touch emulation)", "chrome-mobile": "Chrome, mobile viewport",
            "firefox-mobile": "Firefox, narrow viewport"}.get(n, n)


def walk(suite):
    for s in suite.get("suites", []):
        yield from walk(s)
    for spec in suite.get("specs", []):
        for t in spec.get("tests", []):
            res = t["results"][-1] if t.get("results") else {"status": "skipped", "duration": 0}
            yield spec["title"], res.get("status"), res.get("duration", 0), re.sub(r"\s+", " ", re.sub(r"\x1b\[[0-9;]*m", "", (res.get("error") or {}).get("message", "")))[:140]


runs = []
for f in files:
    data = json.loads(f.read_text(encoding="utf-8"))
    st = data["stats"]
    if st["expected"] + st["unexpected"] + st["skipped"] + st["flaky"] == 0:
        continue  # an aborted launch (e.g. port clash) wrote an empty file: not a run
    rows = [r for top in data["suites"] for r in walk(top)]
    runs.append((label(f), st, rows, data.get("config", {}).get("projects", [{}])[0].get("use", {})))

out = ["# Browser verification record", "",
       "Generated by `python browser-tests/make_report.py` from the JSON files Playwright wrote during actual runs against the real Next.js frontend and an isolated "
       "backend (temporary encrypted data, stubbed paid provider, every real credential blanked).", "",
       "**Reproduce:** `cd browser-tests && npm install && npx playwright test` (Edge, default). Others: `PFI_BROWSER=chrome`, `PFI_BROWSER=firefox` "
       "(after `npx playwright install firefox`), add `PFI_MOBILE=1` for a 390x844 touch viewport. Ports 3100 and 8100 must be free. Then `python make_report.py`.", "",
       "## Runs", "", "| Browser / viewport | Passed | Failed | Skipped | Flaky | Wall time |", "|---|---|---|---|---|---|"]
for name, st, rows, _ in runs:
    out.append(f"| {name} | {st['expected']} | {st['unexpected']} | {st['skipped']} | {st['flaky']} | {round(st['duration'] / 1000)} s |")
out += ["", "## Not covered by any browser run",
        "WebKit/Safari (no WebKit run was made; Safari behaviour is untested), real phones (the mobile run is viewport and touch EMULATION in a desktop engine), "
        "the print/PDF view, accessibility checks, payment flows, the real try-on provider (always stubbed), slow-network behaviour.", ""]
for name, st, rows, _ in runs:
    out += [f"## {name}", "", "| # | Test | Expected | Actual | Duration |", "|---|---|---|---|---|"]
    for i, (title, status, dur, err) in enumerate(rows, 1):
        exp = re.search(r"\[(expect [^\]]+)\]", title)
        actual = "PASS" if status == "passed" else (f"FAIL - {err}" if status in ("failed", "timedOut") else str(status).upper())
        out.append(f"| {i} | {title} | {exp.group(1) if exp else 'see test body'} | {actual} | {dur / 1000:.1f} s |")
    out.append("")
(HERE.parent / "docs" / "BROWSER_VERIFICATION.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(json.dumps({"runs": [(n, s["expected"], s["unexpected"], s["skipped"]) for n, s, _, _ in runs]}))
